test("endpoint rejects cross-origin, unknown fields and oversized bodies", async ({ request }) => {
  const issued = await request.get("/api/report"); const { ticket, pageId } = await issued.json();
  const headers = { origin: "http://localhost:3100", "x-page-ticket": ticket };
  const data = { event: "visit", requestId: pageId, device: "mobile", browser: "Safari", os: "iOS" };
  expect((await request.post("/api/report", { headers: { ...headers, origin: "https://bad.example" }, data })).status()).toBe(403);
  expect((await request.post("/api/report", { headers, data: { ...data, message: "relay" } })).status()).toBe(400);
  expect((await request.post("/api/report", { headers, data: { ...data, note: "a".repeat(5000) } })).status()).toBe(400);
  expect((await request.post("/api/report", { headers, data })).status()).toBe(200);
  expect((await request.post("/api/report", { headers, data })).status()).toBe(200);
});
