import { test, expect } from "@playwright/test";
import { addDays, dateKey } from "../../lib/dates";
test("complete plan, one visit and final, remember, change, ICS, and reset", async ({ page }) => {
  const events: string[] = [], errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  page.on("request", request => { if (request.url().endsWith("/api/report") && request.method() === "POST") events.push(request.postDataJSON().event); });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "i made you something." })).toBeVisible();
  const cat = page.getByRole("button", { name: "Give the cat a little pat" });
  const catImage = cat.getByRole("img");
  await expect(catImage).toBeVisible();
  await expect.poll(() => catImage.evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(720);
  for (let i = 0; i < 5; i++) await cat.click();
  await expect(page.getByRole("status")).toContainText("i love you.");
  await expect.poll(() => cat.locator("video").evaluate(video => (video as HTMLVideoElement).currentTime)).toBeGreaterThan(0);
  await expect(cat.locator("video")).not.toHaveAttribute("loop");
  await page.getByRole("button", { name: "open it" }).click();
  const date = dateKey(addDays(new Date(), 2));
  if (date.slice(0, 7) !== dateKey(new Date()).slice(0, 7)) await page.getByRole("button", { name: "Next month" }).click();
  await page.locator(`[data-date="${date}"]`).click();
  await page.getByRole("button", { name: "food + somewhere pretty" }).click();
  await page.getByRole("button", { name: "sunset", exact: true }).click();
  await page.getByLabel("anything you wanna tell me?").fill("wear the jacket i like");
  await page.getByRole("button", { name: "seal the date" }).dblclick();
  await expect(page.getByRole("heading", { name: "okay. it's a date." })).toBeVisible();
  expect(events.filter(e => e === "visit")).toHaveLength(1);
  expect(events.filter(e => e === "final")).toHaveLength(1);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "save our date" }).click();
  expect((await download).suggestedFilename()).toBe(`our-date-${date}.ics`);
  await page.reload();
  await expect(page.getByRole("heading", { name: "okay. it's a date." })).toBeVisible();
  await expect(page.getByText("wear the jacket i like", { exact: false })).toBeVisible();
  await expect.poll(() => events.filter(e => e === "visit").length).toBe(2);
  expect(events.filter(e => e === "final")).toHaveLength(1);
  await page.getByRole("button", { name: "change it", exact: true }).click();
  await expect(page.getByRole("gridcell", { selected: true })).toHaveCount(1);
  await page.getByRole("button", { name: "seal the date" }).click();
  await page.getByRole("button", { name: "start over" }).click();
  await expect(page.getByRole("button", { name: "open it" })).toBeVisible();
  expect(errors).toEqual([]);
});
test("keyboard calendar, month boundaries and reduced motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("button", { name: "Give the cat a little pat" }).click();
  expect(await page.locator(".cat-video").evaluate(video => (video as HTMLVideoElement).paused)).toBe(true);
  await page.getByRole("button", { name: "open it" }).click();
  const today = page.locator('[aria-current="date"]');
  await today.focus(); await page.keyboard.press("ArrowRight");
  await expect(page.locator(`[data-date="${dateKey(addDays(new Date(), 1))}"]`)).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("gridcell", { selected: true })).toHaveCount(1);
  await page.keyboard.press("PageDown");
  await expect(page.locator(".day:focus")).toHaveCount(1);
  while (await page.getByRole("button", { name: "Next month" }).isEnabled()) await page.getByRole("button", { name: "Next month" }).click();
  await expect(page.locator(`[data-date="${dateKey(addDays(new Date(), 90))}"]`)).toBeEnabled();
  const outOfRange = page.locator(`[data-date="${dateKey(addDays(new Date(), 91))}"]`);
  if (await outOfRange.count()) await expect(outOfRange).toBeDisabled();
});
test("network failure and denied storage never prevent the final card", async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error("blocked"); }; });
  await page.route("**/api/report", route => route.abort());
  await page.goto("/"); await page.getByRole("button", { name: "open it" }).click();
  await page.locator('[aria-current="date"]').click();
  await page.getByRole("button", { name: "seal the date" }).click();
  await expect(page.getByRole("heading", { name: "okay. it's a date." })).toBeVisible();
  await expect(page.getByText("save our date above to keep a copy")).toBeVisible();
});
